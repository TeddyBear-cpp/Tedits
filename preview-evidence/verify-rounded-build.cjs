const fs = require('node:fs');
const assert = require('node:assert/strict');
const {applyContent} = require('../build-sanity.cjs');
const {applyWhyPage, applyEnquiryPage} = require('../service-page-renderer.cjs');
const docs = ['seed.ndjson','service-pages.ndjson'].flatMap(file => fs.readFileSync('studio-teditstudio/'+file,'utf8').trim().split(/\r?\n/).map(JSON.parse));
const home = docs.find(d => d._id === 'homepage');
const why = docs.find(d => d._type === 'whyPage');
const enquiry = docs.find(d => d._type === 'enquiryPage');
assert.ok(why && enquiry, 'Service page fixtures are required');
const source = fs.readFileSync('studio/index.html','utf8');
const rendered = applyContent(source,{homepage:home,projects:docs.filter(d => d._type === 'project')});
assert.ok(rendered.includes('Design that<br><span>connects.</span>'));
assert.equal((rendered.match(/<article class="project/g)||[]).length,5);
const legacy = applyContent(source,{homepage:{...home,heading:'Thoughtful websites.',subheading:'Designed for your business.'}});
assert.ok(legacy.includes('Design that<br><span>connects.</span>'));
const custom = applyContent(source,{homepage:{...home,heading:'Custom & considered',subheading:'Websites.',intro:'A custom introduction.'}});
assert.ok(custom.includes('Custom &amp; considered'));
assert.ok(custom.includes('<p>A custom introduction.</p>'));
const whyHtml = applyWhyPage(fs.readFileSync('studio/why-teditstudio.html','utf8'),why);
assert.ok(whyHtml.includes('id="business-rotation"'));
assert.ok(whyHtml.includes('studio-hero.js'));
assert.ok(!whyHtml.includes('studio-waves.js'));
assert.ok(applyEnquiryPage(fs.readFileSync('studio/enquire.html','utf8'),enquiry,why).includes('https://formspree.io/f/mbggrwra'));
for(const file of ['studio-rounded.css','studio-clouds.js','assets/clouds/sky.webp','assets/clouds/hands.webp','assets/clouds/cloud-bank.webp']) assert.ok(fs.existsSync('_site-video/studio/'+file));
const report={buildReferences:'132 files resolve',cmsHomepage:true,cmsLegacyMigration:true,cmsCustomCopy:true,cmsFiveProjects:true,cmsWhyPage:true,cmsEnquiryPage:true,newAssetsPackaged:true};
fs.writeFileSync('preview-evidence/rounded-build-check.json',JSON.stringify(report,null,2));
console.log(report);
