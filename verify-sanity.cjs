const assert = require('node:assert/strict');
const fs = require('node:fs');
const {applyContent} = require('./build-sanity.cjs');
const {applyHomepageOffer, applyWhyPage, applyEnquiryPage} = require('./service-page-renderer.cjs');
const source = fs.readFileSync('studio/index.html', 'utf8');
const [homepage, ...projects] = fs.readFileSync('studio-teditstudio/seed.ndjson', 'utf8').trim().split('\n').map(JSON.parse);
assert.equal(projects.length, 5);
for (const project of projects) assert.ok(source.includes(`projects/${project.concept}/index.html`));
const rendered = applyContent(source, {homepage, projects});
function section(html, pattern) {
  const match = pattern.exec(html);
  assert.ok(match, `Expected section missing: ${pattern}`);
  return match[0];
}
const work = html => section(html, /<section id="work"[\s\S]*?<\/section>/);
const extras = html => section(html, /<section class="wrap more-work"[\s\S]*?<\/section>/);
assert.equal((work(rendered).match(/<article class="story-reveal project(?: project-reverse)?">/g) || []).length, 3);
assert.deepEqual([...work(rendered).matchAll(/class="project-visual [^"]*" href="projects\/([^/]+)\//g)].map(match => match[1]), ['catering', 'rivet-beam', 'tedeats']);
assert.equal((extras(rendered).match(/<a class="story-reveal"/g) || []).length, 2);
assert.ok(rendered.includes('Olive &amp; Ember'));
assert.ok(rendered.includes('Rivet &amp; Beam'));
assert.ok(rendered.includes('href="enquire.html"'));
assert.ok(rendered.includes('studio-story.js'));
assert.ok(rendered.includes('INDEPENDENT CONCEPT'));
assert.ok(!rendered.includes('undefined'));
const malicious = structuredClone(projects);
malicious[0].description = '<script>alert("x")</script>';
const safe = applyContent(source, {homepage, projects: malicious});
assert.ok(safe.includes('&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;'));
assert.ok(!safe.includes('<script>alert("x")</script>'));
assert.throws(() => applyContent(source, {homepage, projects: [projects[0], projects[0]]}), /Duplicate CMS concept/);
const curated = structuredClone(projects);
curated[0].featured = true;
curated[1].visible = false;
const curatedHtml = applyContent(source, {homepage, projects: curated});
assert.equal((work(curatedHtml).match(/<article class="story-reveal project(?: project-reverse)?">/g)||[]).length,2);
assert.ok(work(curatedHtml).includes('Two independent concepts.'));
assert.ok(!work(curatedHtml).includes('Rivet &amp; Beam'));
assert.ok(rendered.includes('projects/little-joy/index.html'));
assert.ok(extras(rendered).includes('Little Joy Play Co.'));
assert.ok(rendered.includes('projects/tedeats/assets/dinner-alt-1.jpg'));
const legacy = projects.map(project => project.concept === 'tedeats' ? {...project,
  description: 'A seal tracing the planning journey.',
  execution: 'A printed seal follows the planning path.',
  disclaimer: 'AI-generated imagery illustrates imagined events.'} : project);
const migrated = applyContent(source, {homepage, projects: legacy});
assert.ok(migrated.includes('an unfolding letter and a guided planning journey'));
assert.ok(migrated.includes('A bouquet follows a curved route'));
assert.ok(!migrated.includes('AI-generated imagery illustrates imagined events.'));
const hiddenJoy = projects.map(project => project.concept === 'little-joy' ? {...project, visible: false} : project);
assert.ok(!applyContent(source, {homepage, projects: hiddenJoy}).includes('projects/little-joy/index.html'));
const custom = structuredClone(projects);
custom.find(project => project.concept === 'catering').description = 'A custom published purpose for this concept.';
const customExtra = custom.find(project => project.concept === 'afterhours');
customExtra.title = 'MIDNIGHT & Co.';
customExtra.imageUrl = 'https://cdn.sanity.io/images/yjcpyptx/production/fixture-1280x900.png';
const customHtml = applyContent(source, {homepage, projects: custom.reverse()});
assert.ok(work(customHtml).includes('A custom published purpose for this concept.'));
assert.ok(extras(customHtml).includes('MIDNIGHT &amp; Co.'));
assert.ok(extras(customHtml).includes('fixture-1280x900.png?w=1280&amp;h=900&amp;fit=crop&amp;auto=format'));
assert.ok(work(rendered).includes('Help someone picture their occasion'));
assert.ok(work(rendered).includes('03 / EVENT PLANNING'));
const noExtras = projects.map(project => ['afterhours','little-joy'].includes(project.concept) ? {...project, visible:false} : project);
assert.ok(!applyContent(source, {homepage, projects:noExtras}).includes('class="wrap more-work"'));
const badImage = structuredClone(projects);
badImage[0].imageUrl = 'https://example.com/untrusted.png';
assert.throws(() => applyContent(source, {homepage, projects:badImage}), /Unexpected Sanity image URL/);

const servicePages = JSON.parse(fs.readFileSync('studio-teditstudio/service-pages.json', 'utf8'));
const offer = {...servicePages.find(document => document._type === 'whyPage'), startingPrice:375, includedRevisions:4, standardTimeline:'5–7 days', businessExamples:['a bakery', 'a venue & cafe']};
const homeOffer = applyHomepageOffer(rendered, offer);
assert.ok(homeOffer.includes('data-examples="a bakery|a venue &amp; cafe"'));
assert.ok(homeOffer.includes('class="offer-price" data-cms-price>€375</p>'));
assert.equal((homeOffer.match(/data-cms-revisions>4<\/span>/g)||[]).length, 2);
assert.ok(homeOffer.includes('data-cms-timeline>5–7 days</span>'));
assert.ok(homeOffer.includes('data-cms-offer-limit>5</span>'));
assert.ok(homeOffer.includes('Once-off payment'));
assert.ok(homeOffer.includes('Domain and hosting charges are excluded.'));
const legacyOffer = {...offer}; delete legacyOffer.currency; delete legacyOffer.offerClientLimit;
assert.ok(applyHomepageOffer(rendered, legacyOffer).includes('data-cms-price>€375</p>'));
assert.ok(applyHomepageOffer(rendered, {...offer, offerClientLimit:7}).includes('data-cms-offer-limit>7</span>'));
assert.ok(applyHomepageOffer(rendered, {...offer, currency:'GBP'}).includes('data-cms-price>£375</p>'));
assert.equal(homeOffer.match(/<title>[\s\S]*?<\/title>/)[0], rendered.match(/<title>[\s\S]*?<\/title>/)[0]);
const redirect = fs.readFileSync('studio/why-teditstudio.html', 'utf8');
assert.equal(applyWhyPage(redirect, offer), redirect);
const enquirySource = fs.readFileSync('studio/enquire.html', 'utf8');
const enquiry = applyEnquiryPage(enquirySource, servicePages.find(document => document._type === 'enquiryPage'), offer);
for(const text of ['data-cms-price>€375</span>', 'data-cms-revisions>4</span>', 'data-cms-timeline>5–7 days</span>']) assert.ok(enquiry.includes(text));
assert.ok(enquiry.includes('data-cms-offer-limit>5</span>'));
assert.ok(enquiry.includes('Domain registration and website hosting are billed separately.'));
assert.throws(() => applyHomepageOffer(rendered, {...offer, currency:'USD'}), /invalid currency/);
assert.throws(() => applyHomepageOffer(rendered, {...offer, offerClientLimit:0}), /invalid offerClientLimit/);
assert.throws(() => applyHomepageOffer(rendered, {...offer, startingPrice:-1}), /invalid startingPrice/);
assert.throws(() => applyHomepageOffer(rendered, {...offer, businessExamples:['a bakery','a|b']}), /cannot contain/);
console.log('Sanity selected projects, compact extras, escaping, visibility, homepage offer, redirect and enquiry checks passed.');
