const assert = require('node:assert/strict');
const fs = require('node:fs');
const {renderMenus,renderMaterials,renderTracks,applyCatalogues} = require('./catalogue-renderer.cjs');
const docs = fs.readFileSync('studio-teditstudio/catalogues.ndjson','utf8').trim().split('\n').map(JSON.parse);
const files = ['catering','rivet-beam','afterhours'];
const renderers = [renderMenus,renderMaterials,renderTracks];
docs.forEach((doc,i) => {
  const html = fs.readFileSync(`studio/projects/${files[i]}/index.html`,'utf8');
  const rendered = renderers[i](html,doc);
  assert.ok(!rendered.includes('undefined'));
  const edited = structuredClone(doc);
  edited.items.reverse(); edited.items[0].title = '<img src=x onerror=alert(1)>';
  const changed = renderers[i](html,edited);
  assert.ok(!changed.includes('<img src=x'));
  assert.ok(changed.includes('&lt;img src=x') || changed.includes('\\u003cimg src=x'));
  const invalid = structuredClone(doc); invalid.items = [];
  assert.throws(()=>renderers[i](html,invalid), /item count/);
});
const menus = renderMenus(fs.readFileSync('studio/projects/catering/index.html','utf8'),docs[0]);
assert.equal((menus.match(/role="tab"/g)||[]).length,3);
assert.ok(menus.includes('tab-menu0'));
const menuConfig = JSON.parse(menus.match(/<script id="cms-menus" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.equal((menus.match(/id="cms-menus"/g)||[]).length,1);
assert.deepEqual(menuConfig.mealDays.map(day=>day.day),['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday']);
assert.equal(menuConfig.mealDays[0].image,'assets/meal-monday.jpg');
const uploadedDays = structuredClone(docs[0]);
uploadedDays.mealDays[0].imageUrl='https://cdn.sanity.io/images/yjcpyptx/production/photo.jpg';
assert.ok(renderMenus(fs.readFileSync('studio/projects/catering/index.html','utf8'),uploadedDays).includes('https://cdn.sanity.io/images/yjcpyptx/production/photo.jpg'));
const unorderedDays = structuredClone(docs[0]);
[unorderedDays.mealDays[0],unorderedDays.mealDays[1]]=[unorderedDays.mealDays[1],unorderedDays.mealDays[0]];
assert.throws(()=>renderMenus(fs.readFileSync('studio/projects/catering/index.html','utf8'),unorderedDays),/Monday through Saturday/);
const promoDoc = structuredClone(docs[1]);
promoDoc.items[0].promo='Winter offer'; promoDoc.items[0].promoStart='2999-01-01'; promoDoc.items[0].promoEnd='2999-01-31';
const materialHtml = renderMaterials(fs.readFileSync('studio/projects/rivet-beam/index.html','utf8'),promoDoc);
assert.ok(materialHtml.includes('class="availability">Available</p>'));
assert.ok(!materialHtml.includes('>Winter offer</span>'));
const featuredDoc = structuredClone(docs[2]);
featuredDoc.items[0].featured=true; featuredDoc.items[0].status='Upcoming'; featuredDoc.items[0].releaseDate='2099-05-01';
const trackHtml = renderTracks(fs.readFileSync('studio/projects/afterhours/index.html','utf8'),featuredDoc);
assert.ok(trackHtml.includes('Featured · Upcoming · Instrumental'));
assert.ok(trackHtml.includes('2099-05-01'));
const bad = structuredClone(docs[2]); bad.items[0].audioUrl='https://example.com/test.mp3';
assert.throws(()=>renderTracks(fs.readFileSync('studio/projects/afterhours/index.html','utf8'),bad),/asset URL/);
if(process.argv.includes('--preview')) applyCatalogues('_site-video',docs);
console.log('Catalogue rendering, reordering, escaping and validation checks passed.');
